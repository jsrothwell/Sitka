#!/usr/bin/env node
// Generates platform token files from src/tokens/tokens.json:
//   platforms/swift/Sources/SitkaTokens/SitkaTokens.swift  (Swift package, see /Package.swift)
//   platforms/figma/variables.json                         (Figma variable collections, Light/Dark modes)
//   public/downloads/SitkaTokens.swift                     (same Swift file, for the Token Export page)
//   public/downloads/sitka-tokens.json                     (tokens.json as served, for the Token Export page)
//   src/app/tokens.components.css                          (component tier from src/tokens/components.json)
//
// Run: npm run tokens:build   (also runs before `npm run build`)
// CI fails if the committed outputs differ from what this produces.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, tokens, VERSION, leaves, parseColor, toHex, toNumber, resolveValue, writeIfChanged } from "./lib.mjs";

const HEADER = `Generated by scripts/tokens/build.mjs from src/tokens/tokens.json (Sitka ${VERSION}). Do not edit.`;
const themes = tokens.color.themes;

// ── Theme key sanity ───────────────────────────────────────────────────────────
const darkKeys = Object.keys(themes.dark).filter((k) => !k.startsWith("$"));
const lightKeys = Object.keys(themes.light).filter((k) => !k.startsWith("$"));
const missing = [...darkKeys.filter((k) => !lightKeys.includes(k)).map((k) => `light.${k}`), ...lightKeys.filter((k) => !darkKeys.includes(k)).map((k) => `dark.${k}`)];
if (missing.length) {
  console.error(`tokens.json: every theme token needs a value in both themes. Missing: ${missing.join(", ")}`);
  process.exit(1);
}
const THEME_KEYS = darkKeys;

// ── Component tier (src/tokens/components.json) ────────────────────────────────
const componentMap = JSON.parse(readFileSync(resolve(ROOT, "src/tokens/components.json"), "utf8"));
const componentTokens = []; // { path: ["button","primary","background"], role: "accent" }
(function collect(node, path) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith("$")) continue;
    if (typeof v === "string") componentTokens.push({ path: [...path, k], role: v });
    else collect(v, [...path, k]);
  }
})(componentMap, []);
const badRoles = componentTokens.filter((t) => !THEME_KEYS.includes(t.role));
if (badRoles.length) {
  console.error(`components.json references unknown theme tokens: ${badRoles.map((t) => `${t.path.join(".")} → ${t.role}`).join(", ")}`);
  process.exit(1);
}
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const componentCss = `/* ${HEADER.replace("tokens.json", "components.json")} */
/* Component tier: each variable points at a theme token, so it follows light/dark and brand overrides. */
:root {
${componentTokens.map((t) => `  --${t.path.map(kebab).join("-")}: var(--${kebab(t.role)});`).join("\n")}
}
`;

// ── Swift ─────────────────────────────────────────────────────────────────────
const swiftIdent = (s) => {
  const id = String(s).replace(/^(\d+)(xl)$/i, "xl$1").replace(/[^A-Za-z0-9]+(.)/g, (_, c) => c.toUpperCase());
  return /^\d/.test(id) ? `s${id}` : id;
};
const camel = (...parts) => parts.map((p, i) => (i === 0 ? String(p) : String(p).charAt(0).toUpperCase() + String(p).slice(1))).join("");
const rgba = (v) => {
  const { r, g, b, a } = parseColor(v);
  const f = (n) => (n / 255).toFixed(4);
  return `SitkaRGBA(red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}, alpha: ${a})`;
};
const num = (n) => (Number.isInteger(n) ? `${n}` : `${+n.toFixed(4)}`);

// DTCG `$deprecated` (true or a message) becomes a Swift deprecation, per docs/DEPRECATION.md.
const deprecated = (t, indent = "        ") =>
  t?.$deprecated ? `${indent}@available(*, deprecated, message: ${JSON.stringify(typeof t.$deprecated === "string" ? t.$deprecated : "Deprecated Sitka token.")})\n` : "";

const palette = [];
for (const [path, t] of leaves(tokens.color)) {
  if (path[0] === "themes") continue;
  const name = path[0] === "categorical" ? `categorical${path[1]}` : camel(path[0], ...path.slice(1).map((p) => (/^\d+$/.test(p) ? p : swiftIdent(p))));
  palette.push(`        /// \`color.${path.join(".")}\` — ${toHex(parseColor(t.$value))}\n${deprecated(t)}        public static let ${name} = ${rgba(t.$value)}`);
}

const themeProps = THEME_KEYS.map((k) => `${deprecated(themes.dark[k])}        public let ${k}: SitkaRGBA`).join("\n");
const themeInit = (mode) => `    public static let ${mode} = Theme(\n${THEME_KEYS.map((k) => `        ${k}: ${rgba(themes[mode][k].$value)}`).join(",\n")}\n    )`;

const numberEnum = (name, doc, group, transform = (x) => x, keyName = swiftIdent) =>
  `    /// ${doc}\n    public enum ${name} {\n${[...leaves(group)]
    .map(([p, t]) => [p, transform(toNumber(t.$value))])
    .filter(([, v]) => v != null)
    .map(([p, v]) => `        public static let ${keyName(p.join("_"))}: Double = ${num(v)}`)
    .join("\n")}\n    }`;

const swift = `// ${HEADER}
//
// Add with Swift Package Manager: https://github.com/jsrothwell/Sitka (product "SitkaTokens").
// Colours are plain values so this compiles everywhere; SwiftUI helpers are below.

import Foundation

public struct SitkaRGBA: Sendable, Hashable {
    public let red: Double
    public let green: Double
    public let blue: Double
    public let alpha: Double

    public init(red: Double, green: Double, blue: Double, alpha: Double = 1) {
        self.red = red; self.green = green; self.blue = blue; self.alpha = alpha
    }
}

public enum SitkaTokens {
    public static let version = "${VERSION}"

    /// Fixed colours: brand ramp, neutrals, semantic, personalization and categorical.
    public enum Palette {
${palette.join("\n")}
    }

    /// Themed colours. Use \`Color.sitka(\\.accent)\` in SwiftUI to follow light/dark automatically.
    public struct Theme: Sendable, Hashable {
${themeProps}
    }

${themeInit("dark")}

${themeInit("light")}

${numberEnum("Spacing", "Spacing scale in points (`spacing.*`).", tokens.spacing, (x) => x, (k) => `s${k}`)}

${numberEnum("Radius", "Corner radii in points (`borderRadius.*`). `full` is a capsule.", tokens.borderRadius)}

${numberEnum("FontSize", "Font sizes in points (`typography.fontSize.*`).", tokens.typography.fontSize)}

${numberEnum("FontWeight", "CSS font weights (`typography.fontWeight.*`); see `Font.Weight.sitka(_:)`.", tokens.typography.fontWeight)}

${numberEnum("LineHeight", "Line-height multipliers (`typography.lineHeight.*`).", tokens.typography.lineHeight)}

${numberEnum("Duration", "Motion durations in seconds (`motion.duration.*`).", tokens.motion.duration)}

    /// Component tier (src/tokens/components.json): which theme token each component part uses.
    /// Use with \`Color.sitka(SitkaTokens.Component.Button.primaryBackground)\`.
    public enum Component {
${Object.entries(componentMap)
  .filter(([k]) => !k.startsWith("$"))
  .map(([comp]) => {
    const rows = componentTokens
      .filter((t) => t.path[0] === comp)
      .map((t) => `            public static var ${camel(...t.path.slice(1))}: KeyPath<Theme, SitkaRGBA> { \\.${t.role} }`);
    return `        public enum ${comp.charAt(0).toUpperCase() + comp.slice(1)} {\n${rows.join("\n")}\n        }`;
  })
  .join("\n")}
    }
}

#if canImport(SwiftUI)
import SwiftUI
#if canImport(UIKit)
import UIKit
#elseif canImport(AppKit)
import AppKit
#endif

public extension SitkaRGBA {
    var color: Color { Color(.sRGB, red: red, green: green, blue: blue, opacity: alpha) }
}

public extension Color {
    /// A themed Sitka colour that follows the system appearance, e.g. \`Color.sitka(\\.statusSuccessText)\`.
    static func sitka(_ token: KeyPath<SitkaTokens.Theme, SitkaRGBA>) -> Color {
        let light = SitkaTokens.light[keyPath: token]
        let dark = SitkaTokens.dark[keyPath: token]
        #if canImport(UIKit) && !os(watchOS)
        return Color(UIColor { $0.userInterfaceStyle == .dark ? dark.uiColor : light.uiColor })
        #elseif canImport(AppKit)
        return Color(NSColor(name: nil) { appearance in
            appearance.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? dark.nsColor : light.nsColor
        })
        #else
        return light.color
        #endif
    }
}

#if canImport(UIKit)
extension SitkaRGBA {
    var uiColor: UIColor { UIColor(red: red, green: green, blue: blue, alpha: alpha) }
}
#elseif canImport(AppKit)
extension SitkaRGBA {
    var nsColor: NSColor { NSColor(srgbRed: red, green: green, blue: blue, alpha: alpha) }
}
#endif

public extension Font.Weight {
    /// Maps a CSS weight from \`SitkaTokens.FontWeight\` to the nearest SwiftUI weight.
    static func sitka(_ weight: Double) -> Font.Weight {
        switch weight {
        case ..<350: return .light
        case ..<450: return .regular
        case ..<550: return .medium
        case ..<650: return .semibold
        default: return .bold
        }
    }
}
#endif
`;

// ── Figma variables ───────────────────────────────────────────────────────────
// Names match the existing Figma library (theme/accent, space/4, radius/md, …).
const colorVars = [];
for (const [path, t] of leaves(tokens.color)) {
  if (path[0] === "themes") continue;
  if (path[0] === "personalization") continue; // handled below as one variable with Light/Dark values
  const hex = toHex(parseColor(t.$value));
  colorVars.push({ name: path.join("/"), type: "COLOR", values: { Light: hex, Dark: hex } });
}
for (const [hue, modes] of Object.entries(tokens.color.personalization)) {
  if (hue.startsWith("$") || hue === "comment") continue;
  colorVars.push({ name: `personalization/${hue}`, type: "COLOR", values: { Light: toHex(parseColor(modes.light.$value)), Dark: toHex(parseColor(modes.dark.$value)) } });
}
for (const k of THEME_KEYS) {
  const v = (mode) => {
    const c = parseColor(themes[mode][k].$value);
    return c.a === 1 ? toHex(c) : `${toHex(c)}${Math.round(c.a * 255).toString(16).padStart(2, "0")}`;
  };
  colorVars.push({ name: `theme/${k}`, type: "COLOR", values: { Light: v("light"), Dark: v("dark") } });
}
const floatVars = (prefix, group, scopes) =>
  [...leaves(group)]
    .map(([p, t]) => ({ name: `${prefix}/${p.join("/")}`, type: "FLOAT", scopes, values: { Default: toNumber(t.$value) } }))
    .filter((v) => v.values.Default != null);

const figma = {
  $comment: HEADER,
  version: VERSION,
  collections: [
    { name: "Colors", modes: ["Light", "Dark"], variables: colorVars },
    { name: "Spacing", modes: ["Default"], variables: floatVars("space", tokens.spacing, ["GAP", "WIDTH_HEIGHT"]) },
    { name: "Radii", modes: ["Default"], variables: floatVars("radius", tokens.borderRadius, ["CORNER_RADIUS"]) },
    {
      name: "Typography",
      modes: ["Default"],
      variables: [
        ...floatVars("fontSize", tokens.typography.fontSize, ["FONT_SIZE"]),
        ...floatVars("fontWeight", tokens.typography.fontWeight, ["FONT_WEIGHT"]),
        ...floatVars("lineHeight", tokens.typography.lineHeight, ["LINE_HEIGHT"]),
        ...Object.entries(tokens.typography.fontFamily)
          .filter(([k]) => !k.startsWith("$"))
          .map(([k, t]) => ({ name: `fontFamily/${k}`, type: "STRING", scopes: ["FONT_FAMILY"], values: { Default: String(resolveValue(t.$value)).split(",")[0].replace(/['"]/g, "").trim() } })),
      ],
    },
  ],
};

// ── Write ─────────────────────────────────────────────────────────────────────
const outputs = [
  ["platforms/swift/Sources/SitkaTokens/SitkaTokens.swift", swift],
  ["public/downloads/SitkaTokens.swift", swift],
  ["platforms/figma/variables.json", JSON.stringify(figma, null, 2) + "\n"],
  ["public/downloads/sitka-tokens.json", JSON.stringify(tokens, null, 2) + "\n"],
  ["src/app/tokens.components.css", componentCss],
];
for (const [path, content] of outputs) {
  console.log(`${writeIfChanged(path, content) ? "wrote    " : "unchanged"} ${path}`);
}
