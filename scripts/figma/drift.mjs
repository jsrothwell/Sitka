#!/usr/bin/env node
// Compares the variables inside the downloadable Figma library (public/downloads/*.figcraft)
// with platforms/figma/variables.json (generated from tokens.json) and writes
// src/site/home/figma-drift.json. The homepage download card reads that file, so its
// "not in the file yet" note is always accurate.
//
// Run: npm run figma:drift   (also runs before `npm run build`, after tokens:build)
// Pass --strict to exit 1 when the file has drifted (for a release gate).
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, writeIfChanged } from "../tokens/lib.mjs";

const FIGCRAFT = "public/downloads/sitka-design-system.figcraft";
const OUT = "src/site/home/figma-drift.json";

const expected = JSON.parse(readFileSync(resolve(ROOT, "platforms/figma/variables.json"), "utf8"));
const doc = JSON.parse(execFileSync("unzip", ["-p", resolve(ROOT, FIGCRAFT), "document.json"], { maxBuffer: 64 * 1024 * 1024 }).toString("utf8"));

const { collections, variables } = doc.variables;
const byId = new Map(variables.map((v) => [v.id, v]));
const byName = new Map(variables.map((v) => [v.name, v]));
const modeIds = new Map(collections.flatMap((c) => c.modes.map((m) => [`${c.name}/${m.name}`, m.id])));

const hex = (c) => "#" + [c.r, c.g, c.b].map((x) => Math.round(x * 255).toString(16).padStart(2, "0")).join("") + (c.a !== undefined && c.a < 1 ? Math.round(c.a * 255).toString(16).padStart(2, "0") : "");
function valueOf(variable, modeId, depth = 0) {
  const v = variable.values[modeId] ?? Object.values(variable.values)[0];
  if (!v || depth > 8) return null;
  if (v.type === "alias") {
    const target = byId.get(v.value);
    return target ? valueOf(target, Object.keys(target.values).includes(modeId) ? modeId : Object.keys(target.values)[0], depth + 1) : null;
  }
  return v.type === "color" ? hex(v.value) : v.value;
}

const missing = [];
const mismatched = [];
for (const collection of expected.collections) {
  for (const variable of collection.variables) {
    // The file names spacing "space/*" and radii "radius/*" like variables.json; type is matched by name.
    const actual = byName.get(variable.name);
    if (!actual) {
      missing.push(variable.name);
      continue;
    }
    for (const [mode, want] of Object.entries(variable.values)) {
      const fileCollection = collections.find((c) => c.id === actual.collection);
      const modeId = modeIds.get(`${fileCollection?.name}/${mode}`) ?? Object.keys(actual.values)[0];
      const got = valueOf(actual, modeId);
      const same = typeof want === "number" ? Math.abs(Number(got) - want) < 0.01 : String(got).toLowerCase() === String(want).toLowerCase();
      if (!same) mismatched.push({ name: variable.name, mode, file: got, code: want });
    }
  }
}

const report = {
  $comment: "Generated by scripts/figma/drift.mjs. Do not edit.",
  file: FIGCRAFT,
  version: expected.version,
  inSync: missing.length === 0 && mismatched.length === 0,
  missing,
  mismatched,
};
const wrote = writeIfChanged(OUT, JSON.stringify(report, null, 2) + "\n");
console.log(`${wrote ? "wrote    " : "unchanged"} ${OUT}: ${missing.length} missing, ${mismatched.length} mismatched`);
if (process.argv.includes("--strict") && !report.inSync) process.exit(1);
